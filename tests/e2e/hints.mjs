import { chromium, launchOpts, E2E_OUT } from "./env.mjs";
const OUT = E2E_OUT;
const r = [];
const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`);
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, serviceWorkers: "block" });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/notes");
await page.waitForSelector(".sheet");
await sleep(400);
const write = async t => {
  await page.click("[data-journal]");
  await page.keyboard.type(t);
  await page.keyboard.press("Enter");
  await sleep(350);
};
const row = t => page.locator(".jh", { has: page.locator(".jh-l", { hasText: t }) });
const lastToast = () => page.locator(".toast").last().innerText().catch(() => "");
await write("Встретили Лиару Портир во Вратах Балдура, она дала нам 300 зм за виверну.");
await write("Рэй погиб в бою с культистами. Купил зелье за 50 зм.");
await write("Выпили в трактире «Низкий фонарь», Халвар передал письмо.");
ok("three hints shown first", (await page.locator(".jh").count()) === 3);
ok("more button", (await page.locator("[data-act=jh-more]").innerText()).includes("3"));
await page.click("[data-act=jh-more]");
await sleep(250);
const texts = (await page.locator(".jh").allInnerTexts()).join(" | ").replace(/\n/g, " ");
await page.locator(".ja-hints").scrollIntoViewIfNeeded();
await page.screenshot({ path: OUT + "hints-list.png" });
ok("all six hints", (await page.locator(".jh").count()) === 6, texts);
ok("name in base form", texts.includes("Лиара Портир") && !texts.includes("Лиару"), texts);
ok("place in base form", texts.includes("Врата Балдура"), texts);
ok("quoted place found", texts.includes("Низкий фонарь"), texts);
ok("known Халвар not offered", !texts.includes("Халвар"), texts);
ok("place guessed", (await row("Низкий фонарь").locator(".chip.on").innerText()) === "Место");
ok("coins offer both ways", (await row("300").locator("[data-act=jh-coins]").count()) === 2);
ok("gain guessed", (await row("300").locator(".chip.on").innerText()).includes("Получили"));
await page.reload();
await page.waitForSelector(".sheet");
await sleep(400);
ok("hints survive reload", (await page.locator(".jh").count()) === 3);
await page.click("[data-act=jh-more]");
await sleep(250);
await row("300").locator("[data-sign='1']").click();
await sleep(300);
ok("coins added", /\+300/.test(await lastToast()), await lastToast());
ok("coins toast offers undo", (await page.locator(".toast .toast-undo").count()) >= 1);
await page.locator(".toast .toast-undo").last().click();
await sleep(400);
ok("undo brings the hint back", (await row("300").count()) === 1);
await row("300").locator("[data-sign='1']").click();
await sleep(300);
await write("Встретили Лиару Портир во Вратах Балдура, она дала нам 300 зм за виверну.");
ok("applied coins not offered again", (await row("300").count()) === 0);
await row("нет в живых").locator("[data-act=jh-dead]").click();
await sleep(300);
await row("Врата Балдура").locator("[data-act=jh-skip]").click();
await sleep(300);
ok("skipped name gone", (await row("Врата Балдура").count()) === 0);
await write("Снова были во Вратах Балдура.");
ok("one skip is only not now", (await row("Врата Балдура").count()) === 1);
await row("Врата Балдура").locator("[data-act=jh-skip]").click();
await sleep(300);
ok("second skip says never", /больше не предлагаю/.test(await lastToast()), await lastToast());
await write("И опять Врата Балдура шумят.");
ok("ignored name not offered again", (await row("Врата Балдура").count()) === 0);
await write("Итого в казне 742 зм.");
await row("742").locator("[data-sign=set]").click();
await sleep(300);
ok("set exact balance", /теперь 742/.test(await lastToast()), await lastToast());
await row("Лиара").locator("[data-act=jh-make][data-sec=people]").click();
await sleep(400);
ok("editor prefilled in base form", (await page.locator(".modal-back.in input").first().inputValue()) === "Лиара Портир");
await page.locator(".modal-back.in [data-close], .modal-back.in .btn.ghost").first().evaluate(b => b.click());
await sleep(300);
ok("cancel keeps the hint", (await row("Лиара").count()) === 1);
await row("Лиара").locator("[data-act=jh-make][data-sec=people]").click();
await sleep(400);
await page.locator(".modal-back.in .btn.gold").last().evaluate(b => b.click());
await sleep(400);
ok("saved card removes the hint", (await row("Лиара").count()) === 0);
await page.click("[data-journal]");
await page.keyboard.type("Пришли к [[Лиару");
await sleep(250);
const sg = await page.locator(".rt-suggest:not([hidden]) .rt-sg b").allInnerTexts();
ok("link suggest by stem", sg.includes("Лиара Портир"), sg.join(","));
await page.keyboard.press("Enter");
await sleep(100);
ok("link keeps the written form", (await page.inputValue("[data-journal]")).endsWith("[[Лиара Портир|Лиару]]"), await page.inputValue("[data-journal]"));
await page.fill("[data-journal]", "");
await write("Халвар и Лиара Портир спорили в Кендлкипе.");
await page.click("[data-act=notes-section][data-k=people]");
await sleep(300);
ok("Лиара in people", (await page.locator(".jr-entry", { hasText: "Лиара Портир" }).count()) === 1);
ok("Рэй in dead group", (await page.locator(".jr-entry.dead", { hasText: "Рэй" }).count()) === 1);
await page.locator(".jr-entry", { hasText: "Лиара Портир" }).click();
await sleep(400);
const dossier = (await page.locator(".nr-dossier").innerText().catch(() => "")).replace(/\n/g, " ");
ok("dossier first seen", /Впервые/i.test(dossier) && dossier.includes("Сессия 1"), dossier);
ok("dossier often near", /Чаще рядом/i.test(dossier), dossier);
const said = await page.locator(".nr-journal li").allInnerTexts();
ok("card shows journal lines", said.length >= 2 && said.some(s => s.includes("300 зм")), said.join(" | "));
await page.screenshot({ path: OUT + "hints-card.png" });
await page.keyboard.press("Escape");
await sleep(300);
await page.click("[data-act=board]");
await sleep(900);
const edgeCount = await page.locator(".modal-back.in .bd-edge").count();
ok("board has line based edges", edgeCount >= 1, String(edgeCount));
await page.keyboard.press("Escape");
await sleep(300);
await page.click("[data-act=quick-note]");
await sleep(300);
await page.fill("[data-qn-text]", "Новый знакомый Бартоломью из Невервинтера.");
await page.locator("[data-qn-save]").evaluate(b => b.click());
await sleep(400);
ok("quick note outside journal tells about hints", /Скрипт заметил/.test(await lastToast()), await lastToast());
ok("no horizontal scroll", await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
ok("no errors", errors.length === 0, errors.join(" | "));
console.log(r.join("\n"));
await browser.close();

import { chromium, launchOpts, E2E_OUT } from "./env.mjs";
const OUT = E2E_OUT;
const r = [];
const ok = (n, c, x = "") => { r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`); if (process.env.E2E_TRACE) console.log(r[r.length - 1]); };
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, serviceWorkers: "block" });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/notes");
await page.waitForSelector(".sheet");
await sleep(400);
const write = async t => {
  await page.click("[data-journal]");
  await page.keyboard.type(t);
  await page.keyboard.press("Enter");
  await sleep(350);
};
const row = t => page.locator(".ja-hints .jh", { has: page.locator(".jh-l", { hasText: t }) });
const lastToast = () => page.locator(".toast").last().innerText().catch(() => "");
const people = () => page.evaluate(() => {
  const all = JSON.parse(localStorage.getItem("dnd.chars") || "{}")["kirion-thorndike"];
  const list = all && all.notes && all.notes.people;
  return Array.isArray(list) ? list : Object.values(list || {});
});

await write("Маргарет испекла пирог на всех.");
ok("typo asks about the card", (await row("Маргарет").innerText()).includes("Маргарэт Торндайк"), await row("Маргарет").innerText().catch(() => ""));
await row("Маргарет").locator("[data-act=jh-alias]").click();
await sleep(300);
ok("alias saved", /теперь тоже/.test(await lastToast()), await lastToast());
await write("Снова Маргарет ворчит.");
ok("alias now known, no hint", (await row("Маргарет").count()) === 0);
ok("alias text links to the card", (await page.locator("article.note[data-sec=sessions] .wl", { hasText: "Маргарет" }).count()) >= 1);

await write("Мефистофель угрожал нам во сне.");
ok("enemy offered", (await row("Мефистофель").innerText().catch(() => "")).includes("враг"), await row("Мефистофель").innerText().catch(() => ""));
await row("Мефистофель").locator("[data-act=jh-att]").click();
await sleep(300);
ok("attitude toast", /теперь враг/.test(await lastToast()), await lastToast());

await write("Халвар попросил нас найти старый ключ от погреба.");
ok("quest offered", (await row("Задание").innerText().catch(() => "")).includes("Найти старый ключ от погреба"), await row("Задание").innerText().catch(() => ""));
await row("Задание").locator("[data-act=jh-quest]").click();
await sleep(400);
ok("quest editor prefilled", (await page.locator(".modal-back.in input").first().inputValue()) === "Найти старый ключ от погреба");
await page.locator(".modal-back.in .btn.gold").last().evaluate(b => b.click());
await sleep(400);
ok("quest hint gone after save", (await row("Задание").count()) === 0);
await write("Нашли старый ключ под бочкой!");
ok("done offered", (await row("выполнено").count()) === 1, (await page.locator(".ja-hints").innerText().catch(() => "")).replace(/\n/g, " "));
await row("выполнено").locator("[data-act=jh-qdone]").click();
await sleep(300);
await page.click("[data-act=notes-section][data-k=quests]");
await sleep(300);
ok("quest stamped done", (await page.locator(".jr-entry", { hasText: "Найти старый ключ" }).innerText()).length > 0 && (await page.locator(".jr-group", { hasText: "Выполненные" }).locator(".jr-entry", { hasText: "Найти старый ключ" }).count()) === 1);

await page.click("[data-act=notes-section][data-k=people]");
await sleep(300);
await page.click("[data-act=add-note][data-sec=people]");
await sleep(300);
await page.locator(".modal-back.in input").first().fill("Халвар");
await page.locator(".modal-back.in .btn.gold").last().evaluate(b => b.click());
await sleep(400);
ok("doubles banner", (await page.locator(".merge-hints .jh", { hasText: "Халвар" }).count()) === 1);
await page.locator(".merge-hints").scrollIntoViewIfNeeded();
await page.screenshot({ path: OUT + "hints2-merge.png" });
await sleep(1500);
const before = (await people()).length;
await page.locator(".merge-hints [data-act=merge-notes]").first().click();
await sleep(1500);
const after = await people();
ok("merged into one card", after.length === before - 1, `${before} -> ${after.length}`);
const halvar = after.find(p => p.title === "Халвар Торндайк");
ok("short name kept as alias", !!halvar && String(halvar.aliases || "").includes("Халвар"), halvar && halvar.aliases);
ok("merge offers undo", (await page.locator(".toast .toast-undo").count()) >= 1);
await page.locator(".toast .toast-undo").last().click();
await sleep(1500);
ok("undo restores both cards", (await people()).length === before);
await page.locator(".merge-hints [data-act=merge-skip]").first().click();
await sleep(300);
ok("different people stays quiet", (await page.locator(".merge-hints").count()) === 0);
await page.click("[data-act=notes-section][data-k=sessions]");
await sleep(300);
await write("Видели Бартоломью у ворот.");
const bart = row("Бартоломью");
ok("source line hidden at first", !(await bart.locator(".jh-src").isVisible()));
await bart.locator("[data-act=jh-why]").click();
await sleep(200);
ok("why shows the source line", (await bart.locator(".jh-src").innerText()).includes("Видели Бартоломью у ворот"), await bart.locator(".jh-src").innerText().catch(() => ""));
await bart.locator("[data-act=jh-skip]").click();
await sleep(200);
await write("Опять Бартоломью у ворот.");
await row("Бартоломью").locator("[data-act=jh-skip]").click();
await sleep(1500);
const hidden = await page.evaluate(() => (JSON.parse(localStorage.getItem("dnd.chars") || "{}")["kirion-thorndike"].hintIgnore || []).map(x => x.t).join(","));
ok("never list stored in the character", hidden.includes("Бартоломью"), hidden);
await page.click("[data-act=menu]").catch(() => {});
await sleep(400);
const menuItem = page.locator(".modal-back.in [data-m=hint-hidden]");
ok("menu has hidden hints", (await menuItem.count()) === 1);
await menuItem.click();
await sleep(400);
ok("hidden list shows the name", (await page.locator(".modal-back.in .hh-row", { hasText: "Бартоломью" }).count()) === 1);
await page.locator(".modal-back.in .hh-row", { hasText: "Бартоломью" }).locator("[data-hh]").click();
await sleep(300);
await page.keyboard.press("Escape");
await sleep(300);
await write("И снова Бартоломью у ворот.");
ok("returned name is offered again", (await row("Бартоломью").count()) === 1);
await page.locator("article.note[data-sec=sessions] [data-act=edit-note]").first().click();
await sleep(400);
const ta = page.locator(".modal-back.in textarea").first();
await ta.evaluate((el, add) => { el.value = el.value + add; el.dispatchEvent(new Event("input", { bubbles: true })); }, "\nПотом встретили Изольду в таверне.");
await page.locator(".modal-back.in .btn.gold").last().evaluate(b => b.click());
await sleep(500);
ok("edit of an old entry gives hints", (await row("Изольд").count()) === 1, (await page.locator(".ja-hints").innerText().catch(() => "")).replace(/\n/g, " "));
ok("no horizontal scroll", await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
ok("no errors", errors.length === 0, errors.join(" | "));
console.log(r.join("\n"));
await browser.close();

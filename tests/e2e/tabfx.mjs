import { chromium, launchOpts } from "./env.mjs";
const r = [];
const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`);
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 375, height: 812 }, serviceWorkers: "block", hasTouch: true, isMobile: true });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/char");
await page.waitForSelector(".sheet");
await sleep(800);
const ids = await page.evaluate(async () => (await import("/js/tab-fx.js")).VARIANTS.map(v => v.id));
ok("variants listed", ids.length >= 18 && new Set(ids).size === ids.length, String(ids.length));
const calm = () => page.waitForFunction(() => !document.querySelector(".tabfx"), null, { timeout: 5000 }).catch(() => {});
const state = () => page.evaluate(() => ({ layers: document.querySelectorAll(".tabfx").length, body: document.querySelector("[data-body]").dataset.tab, on: document.querySelector(".tab.on").dataset.tab, hscroll: document.documentElement.scrollWidth - document.documentElement.clientWidth }));
const bad = [];
for (const id of ids) {
  await page.evaluate(v => localStorage.setItem("dnd.tabfx", v), id);
  await page.click(".tab[data-tab=spells]");
  await sleep(id === "none" ? 150 : 200);
  const mid = await state();
  await calm();
  const end = await state();
  await page.click(".tab[data-tab=char]");
  await sleep(150);
  await calm();
  const back = await state();
  if (mid.body !== "spells" || end.layers !== 0 || end.body !== "spells" || back.body !== "char" || back.layers !== 0 || end.hscroll || back.hscroll) bad.push(`${id}:${JSON.stringify({ mid, end, back })}`);
}
ok("every variant lands on the right tab and cleans up", bad.length === 0, bad.join("|"));
await page.evaluate(() => localStorage.setItem("dnd.tabfx", "book"));
await page.click(".tab[data-tab=notes]");
await page.click(".tab[data-tab=combat]");
await page.click(".tab[data-tab=features]");
await sleep(2200);
const rapid = await state();
ok("rapid taps end on the last tab", rapid.body === "features" && rapid.on === "features" && rapid.layers === 0, JSON.stringify(rapid));
await page.evaluate(() => localStorage.setItem("dnd.tabfx", "dice"));
await page.click(".tab[data-tab=char]");
await sleep(300);
const blocked = await page.evaluate(() => { const l = document.querySelector(".tabfx"); const r = l.getBoundingClientRect(); return !!l && document.elementFromPoint(r.left + 40, r.top + 40).closest(".tabfx") !== null; });
ok("effect layer blocks stray taps", blocked);
await sleep(2200);
await page.evaluate(() => localStorage.removeItem("dnd.tabfx"));
await page.click(".tab[data-tab=spells]");
await sleep(300);
ok("auto choice is instant under automation", (await page.locator(".tabfx").count()) === 0);
await page.click("[data-act=menu]");
await page.locator(".menu-item", { hasText: "Анимация вкладок" }).click();
await page.waitForSelector(".modal.tabfx-pick");
ok("picker lists variants with weight tags", (await page.locator(".tabfx-pick .fxo").count()) >= 19 && (await page.locator(".tabfx-pick .fxo-tag").count()) >= 18);
await page.locator(".tabfx-pick .fxo[data-id=seal]").click();
ok("picker saves the choice", (await page.evaluate(() => localStorage.getItem("dnd.tabfx"))) === "seal");
await page.locator(".tabfx-pick [data-try]").click();
await sleep(3200);
const tried = await state();
ok("try plays and returns to the same tab", tried.body === "spells" && tried.on === "spells" && tried.layers === 0, JSON.stringify(tried));
ok("no errors", errors.length === 0, errors.join("|"));
await browser.close();
console.log(r.join("\n"));

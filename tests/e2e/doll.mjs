import { chromium, launchOpts, E2E_OUT } from "./env.mjs";
const OUT = E2E_OUT;
const r = [];
const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`);
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, serviceWorkers: "block" });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/inventory");
await page.waitForSelector(".doll");
ok("armor on the body slot", (await page.locator(".dslot[data-slot=body]").innerText()).includes("Проклёпанная кожа"));
ok("dagger in the right hand", (await page.locator(".dslot[data-slot=main]").innerText()).includes("Кинжал"));
ok("extras listed", (await page.locator(".doll-panel .inv-grid .slot").count()) >= 1);
await page.click(".dslot[data-slot=main2]");
await page.waitForSelector(".modal-back.in [data-pick]");
await page.click(".modal-back.in [data-pick]:has-text('Лёгкий арбалет')");
await sleep(300);
ok("crossbow in the spare set takes both hands", (await page.locator(".dslot.two[data-slot=main2]").count()) === 1);
ok("crossbow left the bag", (await page.locator(".inv-carried .slot", { hasText: "Лёгкий арбалет" }).count()) === 0);
await page.click("[data-act=doll-swap]");
await sleep(300);
ok("swap puts crossbow in hand", (await page.locator(".dslot.two[data-slot=main]").innerText()).includes("Лёгкий арбалет"));
ok("dagger goes to the spare set", (await page.locator(".dslot[data-slot=main2]").innerText()).includes("Кинжал"));
await page.screenshot({ path: OUT + "doll-swap.png", fullPage: true });
await page.click(".tab[data-tab=combat]");
await sleep(300);
const names = await page.$$eval(".atk-row .atk-name b", bs => bs.map(b => b.textContent));
ok("combat shows the crossbow", names.includes("Лёгкий арбалет"), names.join(","));
await page.click(".tab[data-tab=inventory]");
await page.click(".dslot[data-slot=main]");
await page.click(".modal-back.in [data-x=off]");
await sleep(300);
ok("unequip empties the hands", (await page.locator(".dslot.empty[data-slot=main]").count()) === 1 && (await page.locator(".inv-carried .slot", { hasText: "Лёгкий арбалет" }).count()) === 1);
await page.click(".dslot[data-slot=head]");
await page.waitForSelector(".modal-back.in .doll-rest");
ok("picker offers other things", (await page.locator(".modal-back.in .doll-rest [data-pick]").count()) > 3);
await page.keyboard.press("Escape");
await page.fill("[data-ui=inv-q]", "кинжал");
await sleep(200);
ok("search dims other doll cells", (await page.locator(".dslot[data-slot=body].dim").count()) === 1 && (await page.locator(".dslot[data-slot=main2].dim").count()) === 0);

const desk = await browser.newContext({ viewport: { width: 1280, height: 1900 }, serviceWorkers: "block" });
await desk.route(/gstatic.com|googleapis.com|google.com/, x => x.abort());
const dp = await desk.newPage();
dp.on("pageerror", e => errors.push(e.message));
{
  const page = dp;
  await page.goto("http://localhost:8765/#/c/kirion-thorndike/inventory");
  await page.waitForSelector(".doll");
  const dragTo2 = async (from, to) => {
    const a = await page.locator(from).first().boundingBox();
    await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
    await page.mouse.down();
    await page.mouse.move(a.x + a.width / 2 + 10, a.y + a.height / 2 + 10, { steps: 3 });
    const b = await page.locator(to).first().boundingBox();
    await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 8 });
    await page.mouse.up();
    await sleep(350);
  };
  await dragTo2(".doll-extra .slot:has-text('Лёгкий арбалет')", ".dslot[data-slot=main]");
  ok("drag crossbow onto the right hand", (await page.locator(".dslot.two[data-slot=main]").innerText()).includes("Лёгкий арбалет"));
  ok("dagger swaps into the crossbow place", (await page.locator(".doll-extra .slot", { hasText: "Кинжал" }).count()) === 1);
  await dragTo2(".doll-extra .slot:has-text('Кинжал')", ".inv-carried .inv-grid");
  ok("drag to the bag takes it off", (await page.locator(".inv-carried .slot", { hasText: "Кинжал" }).count()) === 1);
  ok("no modal after drag", (await page.locator(".modal-back.in").count()) === 0);
  await dragTo2(".dslot[data-slot=main]", ".inv-carried .inv-grid");
  ok("drag off the doll unequips", (await page.locator(".dslot.empty[data-slot=main]").count()) === 1);
  await dragTo2(".inv-carried .slot:has-text('Кинжал')", ".inv-carried .slot.box:has-text('Рюкзак')");
  ok("drop on a backpack puts it inside", (await page.locator(".box-pop:not([hidden])", { hasText: "Кинжал" }).count()) === 1);
  await dragTo2(".box-pop:not([hidden]) .slot:has-text('Кинжал')", ".dslot[data-slot=body]");
  ok("unfit slot refuses", (await page.locator("#toasts .toast", { hasText: "Сюда не наденешь" }).count()) === 1);
  await page.click(".inv-carried .slot.box:has-text('Рюкзак')");
  await sleep(200);
  ok("tap closes the backpack", (await page.locator(".box-pop[hidden]", { hasText: "Кинжал" }).count()) === 1);
  await page.screenshot({ path: OUT + "doll-desk.png", fullPage: true });
}
await desk.close();
ok("no errors", errors.length === 0, errors.join("|"));
await browser.close();
console.log(r.join("\n"));

import { chromium, launchOpts, E2E_OUT } from "./env.mjs";
const r = [];
const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`);
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: "block" });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/spells");
await page.waitForSelector(".sheet");
const spells = await page.locator(".sheet").innerText();
ok("seal of Kania is in spells", spells.includes("Печать Кании"));
await page.click(".tab[data-tab=features]");
await sleep(300);
const feats = await page.locator(".sheet").innerText();
ok("spell recognition replaces contract genius", feats.includes("Узнавание заклинаний") && !feats.includes("Гений договоров"));
await page.click(".tab[data-tab=notes]");
await sleep(300);
await page.locator(".sheet").getByText("Прочее", { exact: true }).first().click();
await sleep(300);
const notes = await page.locator(".sheet").innerText();
ok("law notes listed", notes.includes("Закон о магии") && notes.includes("Уголовный кодекс"));
ok("rules note listed", notes.includes("Правила и ритм игры"));
await page.getByText("Закон о магии (кратко)").first().click();
await sleep(400);
await page.screenshot({ path: E2E_OUT + "dmhome-notes.png" });

await page.evaluate(() => {
  const all = JSON.parse(localStorage.getItem("dnd.chars"));
  const c = all["kirion-thorndike"];
  const drop = (o, id) => { if (Array.isArray(o)) return o.filter(x => x.id !== id); for (const k of Object.keys(o)) if (k === id || (o[k] && o[k].id === id)) delete o[k]; return o; };
  c.spells = drop(c.spells, "sp-kania-seal");
  c.features = drop(c.features, "g-spell-recognition");
  const old = { id: "g-contract-genius", name: "Гений договоров", nameEn: "Contract Genius", category: "gift", source: "own", action: "passive" };
  if (Array.isArray(c.features)) c.features.push(old); else c.features[old.id] = old;
  c.notes.misc = drop(c.notes.misc, "n-law-magic");
  localStorage.setItem("dnd.chars", JSON.stringify(all));
});
await page.goto("http://localhost:8765/#/c/kirion-thorndike/spells");
await page.reload();
await page.waitForSelector(".sheet");
await page.click("[data-act=menu]");
ok("gifts button shown on an older sheet", await page.locator(".modal-back.in [data-m=dm-gifts]").count() === 1);
await page.click(".modal-back.in [data-m=dm-gifts]");
await sleep(300);
await page.locator(".modal-back.in button", { hasText: "Добавить" }).last().click();
await sleep(2500);
const stored = await page.evaluate(() => { const c = JSON.parse(localStorage.getItem("dnd.chars"))["kirion-thorndike"]; const ids = o => (Array.isArray(o) ? o.map(x => x.id) : Object.keys(o)); return { spells: ids(c.spells), features: ids(c.features), misc: ids(c.notes.misc) }; });
ok("gifts applied and saved", stored.spells.includes("sp-kania-seal") && stored.features.includes("g-spell-recognition") && !stored.features.includes("g-contract-genius") && stored.misc.includes("n-law-magic"), JSON.stringify(stored.features.filter(x => /genius|recognition/.test(x))));
await page.click("[data-act=menu]");
ok("gifts button gone when everything is there", await page.locator(".modal-back.in [data-m=dm-gifts]").count() === 0);
await page.keyboard.press("Escape");
await page.goto("http://localhost:8765/#/");
ok("no errors", errors.length === 0, errors.join("|"));
await browser.close();
console.log(r.join("\n"));

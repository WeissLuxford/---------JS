import { chromium, launchOpts, E2E_OUT } from "./env.mjs";
const r = [];
const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`);
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, serviceWorkers: "block" });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/spells");
await page.waitForSelector(".sheet");
const spells = await page.locator(".sheet").innerText();
ok("seal of Kania is in spells", spells.includes("Печать Кании"));
await page.click(".tab[data-tab=features]");
await sleep(300);
const feats = await page.locator(".sheet").innerText();
ok("spell recognition replaces contract genius", feats.includes("Узнавание заклинаний") && !feats.includes("Гений договоров"));
await page.click(".tab[data-tab=notes]");
await sleep(300);
await page.locator(".sheet").getByText("Прочее", { exact: true }).first().click();
await sleep(300);
const notes = await page.locator(".sheet").innerText();
ok("law notes listed", notes.includes("Закон о магии") && notes.includes("Уголовный кодекс"));
await page.getByText("Закон о магии (кратко)").first().click();
await sleep(400);
await page.screenshot({ path: E2E_OUT + "dmhome-notes.png" });
ok("no errors", errors.length === 0, errors.join("|"));
await browser.close();
console.log(r.join("\n"));

import { chromium, launchOpts, E2E_OUT } from "./env.mjs";
const OUT = E2E_OUT;
const r = [];
const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`);
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, serviceWorkers: "block" });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/notes");
await page.waitForSelector(".sheet");
await sleep(400);
const write = async t => {
  await page.click("[data-journal]");
  await page.keyboard.type(t);
  await page.keyboard.press("Enter");
  await sleep(350);
};
const row = t => page.locator(".ja-hints .jh", { has: page.locator(".jh-l", { hasText: t }) });
const lastToast = () => page.locator(".toast").last().innerText().catch(() => "");
const M = ".modal-back.in";

ok("questions section exists", (await page.locator(".jr-tabs [data-act=notes-section][data-k=questions]").count()) === 1);
await write("Почему Мефистофель молчит про старый контракт?");
ok("question hint", (await row("Вопрос").count()) === 1, (await page.locator(".ja-hints").innerText().catch(() => "")).replace(/\n/g, " "));
await row("Вопрос").locator("[data-act=jh-ask]").click();
await sleep(300);
ok("sealed toast", /Запечатано/.test(await lastToast()), await lastToast());
await write("Почему Мефистофель молчит про старый контракт?");
ok("same question not offered twice", (await row("Вопрос").count()) === 0);
await write("Мефистофель отмахнулся, когда спросили про контракт с Кирионом.");
await write("Купили хлеба.");
await page.click("[data-act=notes-section][data-k=questions]");
await sleep(300);
ok("letter in sealed group", (await page.locator(".jr-group", { hasText: "Невскрытые" }).locator(".jr-entry", { hasText: "контракт" }).count()) === 1);
ok("wax seal medal", (await page.locator(".jr-entry .jr-medal.seal:not(.broken)").count()) === 1);
await page.screenshot({ path: OUT + "letters-list.png" });
await page.locator(".jr-entry", { hasText: "контракт" }).click();
await sleep(400);
const clues = await page.locator(`${M} .nr-clues li`).allInnerTexts();
ok("clue gathered from journal", clues.length === 1 && clues[0].includes("отмахнулся"), clues.join(" | "));
await page.screenshot({ path: OUT + "letters-card.png" });
await page.keyboard.press("Escape");
await sleep(300);
await page.click("[data-act=notes-section][data-k=sessions]");
await sleep(300);
await write("Оказалось, Мефистофель молчит, потому что контракт старше Кириона и подписан его отцом.");
ok("answer hint", (await row("Похоже на ответ").count()) === 1, (await page.locator(".ja-hints").innerText().catch(() => "")).replace(/\n/g, " "));
await row("Похоже на ответ").locator("[data-act=jh-answer]").click();
await sleep(400);
ok("answer prefilled", (await page.locator(`${M} textarea`).first().inputValue()).includes("подписан его отцом"));
await page.locator(`${M} .btn.gold`).last().evaluate(b => b.click());
await sleep(400);
ok("opened toast", /вскрыто/i.test(await lastToast()), await lastToast());
ok("answer hint gone", (await row("Похоже на ответ").count()) === 0);
await page.click("[data-act=notes-section][data-k=questions]");
await sleep(300);
ok("letter moved to opened", (await page.locator(".jr-group", { hasText: "Вскрытые" }).locator(".jr-entry", { hasText: "контракт" }).count()) === 1);
await page.locator(".jr-entry", { hasText: "контракт" }).click();
await sleep(400);
ok("answer shown in card", (await page.locator(`${M} .nr-answer`).innerText()).includes("подписан его отцом"));
ok("reseal button", (await page.locator(`${M} [data-act=q-reseal]`).count()) === 1);
await page.locator(`${M} [data-act=q-reseal]`).click();
await sleep(400);
ok("resealed", (await page.locator(".jr-group", { hasText: "Невскрытые" }).locator(".jr-entry", { hasText: "контракт" }).count()) === 1);
ok("no horizontal scroll", await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
ok("no errors", errors.length === 0, errors.join(" | "));
console.log(r.join("\n"));
await browser.close();

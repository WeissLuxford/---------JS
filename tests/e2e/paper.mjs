import { chromium, launchOpts } from "./env.mjs";
const r = [];
const ok = (n, c, x = "") => r.push(`${c ? "PASS" : "FAIL"} ${n}${x ? " :: " + x : ""}`);
const sleep = ms => new Promise(res => setTimeout(res, ms));
const browser = await chromium.launch(launchOpts);
const ctx = await browser.newContext({ viewport: { width: 430, height: 900 }, serviceWorkers: "block" });
await ctx.route(/gstatic\.com|googleapis\.com|google\.com/, x => x.abort());
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto("http://localhost:8765/#/c/kirion-thorndike/notes");
await page.waitForSelector(".sheet");
await sleep(500);
await page.locator("textarea").first().fill("Пришли в порт, говорили с [[Рэй]]");
await page.locator("button", { hasText: "Записать" }).first().click();
await sleep(500);
ok("ink class on the new entry", await page.locator(".tl-e.ink").count() === 1);
ok("pen follows the ink", await page.locator(".tl-e .pen").count() === 1);
await sleep(1500);
ok("ink class removed afterwards", await page.locator(".tl-e.ink").count() === 0 && await page.locator(".tl-e .pen").count() === 0);
const jr = await page.evaluate(() => getComputedStyle(document.querySelector('article.note[data-sec="sessions"]')).backgroundImage);
ok("journal card is paper", jr.includes("gradient") && jr.includes("246, 220"), jr.slice(0, 80));
await page.locator(".sheet").getByText("Люди", { exact: true }).first().click();
await sleep(300);
await page.locator(".jr-entry").first().click();
await sleep(700);
const modal = await page.evaluate(() => {
  const m = document.querySelector(".modal.note-read");
  const s = getComputedStyle(m);
  return { color: s.color, bg: s.backgroundColor, anim: s.animationName };
});
ok("reader is paper with ink text", modal.color === "rgb(44, 29, 16)" && modal.bg === "rgb(227, 209, 168)", JSON.stringify(modal));
ok("reader unfolds", modal.anim === "paper-unfold");
const firstTitle = await page.locator(".modal.note-read h2").innerText();
await page.locator(".modal.note-read .tag, .modal.note-read .nr-back .tag").first().click();
await sleep(120);
ok("page turns on navigation", await page.locator(".modal.note-read .nr.flip").count() === 1);
await sleep(700);
ok("flip class removed", await page.locator(".modal.note-read .nr.flip").count() === 0);
ok("navigation changed the note", (await page.locator(".modal.note-read h2").innerText()) !== firstTitle);
await page.keyboard.press("Escape");
await sleep(300);
await page.evaluate(async () => {
  const { sealFx } = await import("/js/paper-fx.js");
  sealFx("crack");
});
ok("seal cracks", await page.locator(".seal-fx.crack .sf > i").count() === 2);
await sleep(1300);
ok("seal removed", await page.locator(".seal-fx").count() === 0);
await page.evaluate(async () => {
  const { sealFx } = await import("/js/paper-fx.js");
  sealFx("stamp");
});
ok("seal stamps", await page.locator(".seal-fx.stamp .sf > i").count() === 1);
await sleep(1300);
await page.evaluate(() => localStorage.setItem("dnd.lite", "1"));
await page.evaluate(async () => {
  const { sealFx } = await import("/js/paper-fx.js");
  sealFx("crack");
});
const lite = await page.evaluate(() => ({ cls: document.documentElement.className + " " + document.body.className, n: document.querySelectorAll(".seal-fx").length }));
ok("lite mode skips the effect", lite.n === 0, JSON.stringify(lite));
ok("no errors", errors.length === 0, errors.join("|"));
await browser.close();
console.log(r.join("\n"));
